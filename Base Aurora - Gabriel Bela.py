def criar_modulo(nome, tipo):
    return {
        "nome": nome,
        "tipo": tipo,
        "combustivel": None,
        "massa": None,
        "criticidade": None,
        "eta_orbita_min": None,
        "energia_kwh": None,
        "status": "AGUARDANDO"
    }

fila_principal = []
lista_pousados = []
lista_espera = []
lista_alerta = []
pilha_log = []

def enfileirar(fila, modulo):
    fila.append(modulo)

def desenfileirar(fila):
    if len(fila) == 0:
        return None
    primeiro = fila[0]
    del fila[0]
    return primeiro

def log_evento(msg):
    pilha_log.append(msg)

